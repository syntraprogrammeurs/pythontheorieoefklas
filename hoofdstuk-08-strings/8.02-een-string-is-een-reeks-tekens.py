# Hoofdstuk 8 — Strings
# 8.2 Een string is een reeks tekens

naam = "Leeslamp"

print(len(naam))       # 8
print(naam[0])         # L  — het eerste teken
print(naam[1])         # e
print(naam[7])         # p  — het laatste
print(naam[-1])        # p  — ook het laatste, van achteren geteld
print(naam[-2])        # m


# Verwachte uitvoer:
# 8
# L
# e
# p
# p
# m
