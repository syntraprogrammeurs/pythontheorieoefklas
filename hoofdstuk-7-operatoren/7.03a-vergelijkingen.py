# 7.3 Vergelijkingen

print(5 == 5)      # True   gelijk aan
print(5 != 3)      # True   niet gelijk aan
print(5 < 3)       # False  kleiner dan
print(5 <= 5)      # True   kleiner dan of gelijk aan
print(5 > 3)       # True   groter dan
print(5 >= 6)      # False  groter dan of gelijk aan
