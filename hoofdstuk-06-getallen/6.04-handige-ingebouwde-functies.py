# 6.4 Handige ingebouwde functies voor getallen

print(abs(-7))              # 7      — de absolute waarde
print(round(3.567, 2))      # 3.57   — afronden op 2 cijfers
print(round(3.5))           # 4
print(round(2.5))           # 2      — let op!
print(min(4, 9, 2))         # 2
print(max(4, 9, 2))         # 9
print(pow(2, 10))           # 1024   — hetzelfde als 2 ** 10
