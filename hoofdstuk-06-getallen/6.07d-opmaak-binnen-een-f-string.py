# 6.7 Netjes tonen: de f-string — Opmaak binnen een f-string
#
# Voor tabellen in de terminal is uitlijnen goud waard:

print(f"{'Boek':<30}{'Prijs':>8}")
print(f"{'De ontdekking van de hemel':<30}{24.95:>8.2f}")
print(f"{'Het diner':<30}{12.50:>8.2f}")


# Verwachte uitvoer:
# Boek                             Prijs
# De ontdekking van de hemel       24.95
# Het diner                        12.50
