# 7.11 Lidmaatschap: in en not in

leden = ["Anke", "Bram", "Cato"]

print("Bram" in leden)          # True
print("Dirk" in leden)          # False
print("Dirk" not in leden)      # True

print("boek" in "het boek ligt daar")   # True — werkt ook op tekst
